// Writes public/js/config.js from environment variables.
// Vercel runs this as the build step; locally it reads .env.local (or .env).
// Only the PUBLIC Supabase key belongs here. The script refuses secret / service_role keys.
import { readFileSync, writeFileSync, existsSync } from "node:fs";

function loadEnvFile(file) {
  if (!existsSync(file)) return;
  for (const line of readFileSync(file, "utf8").split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Za-z0-9_]+)\s*=\s*(.*?)\s*$/);
    if (m && !(m[1] in process.env)) process.env[m[1]] = m[2].replace(/^["']|["']$/g, "");
  }
}
loadEnvFile(".env.local");
loadEnvFile(".env");

const pick = (...names) => (names.map((n) => process.env[n]).find((v) => v && v.trim()) || "").trim();
const supabaseUrl = pick("SUPABASE_URL", "NEXT_PUBLIC_SUPABASE_URL", "VITE_SUPABASE_URL").replace(/\/+$/, "");
const supabaseKey = pick(
  "SUPABASE_PUBLISHABLE_KEY", "NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY",
  "SUPABASE_ANON_KEY", "NEXT_PUBLIC_SUPABASE_ANON_KEY", "VITE_SUPABASE_ANON_KEY"
);

function isSecretKey(key) {
  if (key.startsWith("sb_secret_")) return true;
  const parts = key.split(".");
  if (parts.length === 3) {
    try { return JSON.parse(Buffer.from(parts[1], "base64url").toString()).role === "service_role"; } catch { return false; }
  }
  return false;
}
if (supabaseKey && isSecretKey(supabaseKey)) {
  console.error("✗ Refusing to build: the Supabase key is a SECRET / service_role key. Use the publishable (anon) key.");
  process.exit(1);
}
if (supabaseUrl && !/^https:\/\/[a-z0-9-]+\.supabase\.(co|in)$/i.test(supabaseUrl) && !/^https?:\/\/(localhost|127\.0\.0\.1)/.test(supabaseUrl)) {
  console.warn("! SUPABASE_URL looks unusual:", supabaseUrl);
}

const buildId = (process.env.VERCEL_GIT_COMMIT_SHA || "").slice(0, 8) || Date.now().toString(36);
const config = { supabaseUrl, supabaseKey, buildId };
writeFileSync("public/js/config.js",
  "// Generated by scripts/write-config.mjs — do not edit or commit.\n" +
  "self.VELOXIA_CONFIG = " + JSON.stringify(config, null, 2) + ";\n");

console.log(supabaseUrl && supabaseKey
  ? `✓ Supabase connected: ${supabaseUrl} (build ${buildId})`
  : `! No Supabase settings found: the app will run in local-only offline mode (build ${buildId}).`);
